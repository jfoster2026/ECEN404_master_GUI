def format_load(value):
    if value >= 1e6 and value % 1e6 == 0:
        return f'{value / 1e6:g} MΩ'
    if value >= 1e3 and value % 1e3 == 0:
        return f'{value / 1e3:g} kΩ'
    return f'{value:g} Ω'


def plot_sensitivity(axes, data):
    """NRMSE against dose rate and PCD width, one line per load; returns the points plotted."""
    for axis in axes:
        axis.clear()
    plotted = 0
    for axis, feature in zip(axes, ('dose_rate', 'pcd_fwhm_ns')):
        report = data.get(feature)
        if report is None:
            continue
        by_load = {}
        for point in report.get('points', []):
            if (isfinite(point['value']) and isfinite(point['nrmse_pct']) and
                    isfinite(point['load_ohm'])):
                load = float(point['load_ohm'])
                by_load.setdefault(load, {}).setdefault(float(point['value']), []).append(
                    (int(point['shot_id']), float(point['nrmse_pct'])))
        load_groups = sorted(by_load)
        for index, load in enumerate(load_groups):
            values = by_load[load]
            x = sorted(values)
            y = [sum(score for _, score in values[value]) / len(values[value])
                 for value in x]
            test_count = len({shot_id for scores in values.values()
                              for shot_id, _ in scores})
            palette = colormaps['Set2'].colors
            color = palette[index % len(palette)]
            axis.plot(x, y, marker='o', markersize=4, linewidth=1.5,
                      color=color, label=f'{format_load(load)} (n={test_count})')
            plotted += len(x)
        axis.set_xlabel(SENSITIVITY_FEATURES[feature])
        axis.set_ylabel(NRMSE_LABEL)
        axis.set_title(f'NRMSE vs. {SENSITIVITY_FEATURES[feature]}')
        axis.grid(True, alpha=.25)
    if plotted:
        axes[0].legend(title='Baseline load group', bbox_to_anchor=(1.02, 1),
                       loc='upper left', fontsize='small')
    return plotted


