    def _start_worker(self, operation, event, *, error_event='error'):
        self._set_busy(True)
        self._set_training(event in ('result', 'batch_result', 'sensitivity_result',
                                     'compare_plan', 'compare_result'))

        def work():
            try:
                self.events.put((event, operation()))
            except Exception as error:
                self.events.put((error_event, str(error)))

        Thread(target=work, daemon=True, name='smaj-model-worker').start()

