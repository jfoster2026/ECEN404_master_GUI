def common_tests(data_by_model):
    return sorted(set.intersection(*(set(map(int, data.shot_id)) for data in data_by_model.values())))


def restrict(data, tests):
    subset = data.loc[data.shot_id.isin(tests)].sort_values('shot_id').reset_index(drop=True)
    # Drop the stored results: pandas compares attrs when concatenating, and they hold frames.
    subset.attrs = {}
    return subset


def best_model(column, values):
    """Name of the best model for one statistic; '' if none is finite, 'Tie' if equal."""
    finite = {model: value for model, value in values.items() if isfinite(value)}
    if not finite:
        return ''
    if column.endswith('_r2'):
        score = {model: -value for model, value in finite.items()}
    elif column.endswith('_phase_error_ns'):
        score = {model: abs(value) for model, value in finite.items()}
    else:  # NRMSE and FLOPs: lower is better.
        score = finite
    best = min(score.values())
    winners = [model for model, value in score.items() if np.isclose(value, best, rtol=1e-12, atol=0)]
    return winners[0] if len(winners) == 1 else 'Tie'


def nrmse_by_test(data_by_model, view, tests):
    column = f'{view}_nrmse_pct'
    return pd.DataFrame({model: restrict(data, tests).set_index('shot_id')[column].astype(float)
                         for model, data in data_by_model.items()})


COST_COLUMNS = ('pytorch_flops_per_prediction', 'operations_per_prediction')
COST_COLUMN = 'flops_per_prediction'
COST_HEADING = 'FLOPs per prediction'
COMPARISON_COST_NOTE = ('FLOPs per prediction (full waveform, one prediction, no training): '
             'Siamese, KAN and Tabular are PyTorch-counted FLOPs (built-in operator formulas only; '
             'Tabular counts its queries after the context is encoded); '
             'PINN and DPM are the native package\'s covered-arithmetic estimates.')


def merge_cost(report):
    """Each model reports one kind of cost; put either in one shared column."""
    present = [column for column in COST_COLUMNS if column in report]
    if not present:
        return report
    merged = report[present].bfill(axis=1).iloc[:, 0]
    report = report.drop(columns=present)
    report[COST_COLUMN] = merged.to_numpy(float)
    return report


def summary_table(data_by_model, view):
    """One row per reported statistic with each model's total."""
    tests = common_tests(data_by_model)
    reports = {model: batch_report(restrict(data, tests), view) for model, data in data_by_model.items()}
    columns = list(dict.fromkeys(column for report in reports.values() for column in report.columns[1:]))
    if len(set(COST_COLUMNS) & set(columns)) > 1:  # Mixed cost kinds share one row.
        reports = {model: merge_cost(report) for model, report in reports.items()}
        columns = list(dict.fromkeys(column for report in reports.values() for column in report.columns[1:]))
    rows = []
    for column in columns:
        values = {model: float(report.iloc[-1][column]) if column in report else float('nan')
                  for model, report in reports.items()}
        heading = COST_HEADING if column == COST_COLUMN else HEADINGS[column]
        rows.append(dict(statistic=heading, column=column, **values))
    return pd.DataFrame(rows)


def per_test_table(data_by_model, view):
    """Each common test's NRMSE and R² for every model, and the lowest-NRMSE model."""
    tests = common_tests(data_by_model)
    nrmse = nrmse_by_test(data_by_model, view, tests)
    table = pd.DataFrame({'Test': tests})
    for model in data_by_model:
        table[f'{model} NRMSE (%)'] = nrmse[model].to_numpy()
    for model, data in data_by_model.items():
        table[f'{model} R²'] = restrict(data, tests)[f'{view}_r2'].to_numpy(float)
    table['Lowest NRMSE'] = [best_model(f'{view}_nrmse_pct', row.to_dict()) for _, row in nrmse.iterrows()]
    return table


def export_table(data_by_model):
    """Long table of every model and window on the common tests, with totals rows."""
    tests = common_tests(data_by_model)
    frames = []
    for model, data in data_by_model.items():
        for view in VIEWS:
            report = merge_cost(batch_report(restrict(data, tests), view))
            report.columns = [column.removeprefix(f'{view}_') for column in report.columns]
            frames.append(report.assign(model=model, window=VIEW_LABELS[view]))
    export = pd.concat(frames, ignore_index=True)
    return export[['model', 'window', *[column for column in export.columns if column not in ('model', 'window')]]]


def _format(value):
    if isinstance(value, str):
        return value
    return f'{value:,.3f}' if isfinite(value) else 'N/A'


