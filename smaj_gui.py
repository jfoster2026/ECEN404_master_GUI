CHECKED, UNCHECKED, UNAVAILABLE = '☑', '☐', '—'


def open_in_file_browser(folder):
    if sys.platform == 'win32':
        os.startfile(folder)
    else:
        subprocess.Popen(['open' if sys.platform == 'darwin' else 'xdg-open', str(folder)])


def _number(value, unit=''):
    try:
        return f'{float(value):.3g}{unit}'
    except (TypeError, ValueError):
        return ''


class TestChecklistWindow(tk.Toplevel):
    """Edits a working copy of the exclusions; nothing changes until Apply."""

    def __init__(self, parent, library, models, on_close):
        super().__init__(parent)
        self.library = library
        self.models = models  # {key: display name}
        self.on_close = on_close
        self.excluded = {model: library.excluded_for(model) for model in models}
        self.entries = {}
        self.disk_changed = False
        self.title('Choose tests for each model')
        self.transient(parent)
        self.geometry(f'{min(1200, parent.winfo_screenwidth()-80)}x{min(640, parent.winfo_screenheight()-120)}')
        self.minsize(820, 440)
        self.protocol('WM_DELETE_WINDOW', self.cancel)
        self.folder_text = tk.StringVar(self)
        self.summary = tk.StringVar(self)
        self._build()
        self.rescan()
        self.grab_set()

    def _build(self):
        content = ttk.Frame(self, padding=16)
        content.pack(fill='both', expand=True)
        ttk.Label(content, text='Click a check box to include or exclude a test for that model. '
                  'Excluded tests are neither modeled nor used for training.',
                  font=('Segoe UI', 10)).pack(anchor='w')
        folder = ttk.Frame(content)
        folder.pack(fill='x', pady=(10, 10))
        ttk.Label(folder, textvariable=self.folder_text, font=('Segoe UI', 9)).pack(side='left', fill='x', expand=True)
        ttk.Button(folder, text='Rescan', command=self.rescan).pack(side='right')
        ttk.Button(folder, text='Change folder…', command=self.change_folder).pack(side='right', padx=(0, 8))
        ttk.Button(folder, text='Open new-tests folder', command=self.open_folder).pack(side='right', padx=(0, 8))

        columns = ('test', 'source', 'dose', 'bias', 'load', 'width', *self.models, 'status')
        frame = ttk.Frame(content)
        frame.pack(fill='both', expand=True)
        frame.rowconfigure(0, weight=1)
        frame.columnconfigure(0, weight=1)
        self.table = ttk.Treeview(frame, columns=columns, show='headings', selectmode='browse', style='Stats.Treeview')
        scroll = ttk.Scrollbar(frame, orient='vertical', command=self.table.yview)
        self.table.configure(yscrollcommand=scroll.set)
        titles = {'test': 'Test', 'source': 'Source', 'dose': 'Dose rate', 'bias': 'Bias',
                  'load': 'Load', 'width': 'PCD width', 'status': 'Status', **self.models}
        for column in columns:
            model = column in self.models
            self.table.heading(column, text=titles[column])
            self.table.column(column, anchor='center' if model else 'w', stretch=column == 'status',
                              width=80 if model else 200 if column == 'status' else 90)
        self.table.tag_configure('unavailable', foreground='#8a96a5')
        self.table.grid(row=0, column=0, sticky='nsew')
        scroll.grid(row=0, column=1, sticky='ns')
        self.table.bind('<Button-1>', self._click)
        self.table.bind('<Double-1>', lambda event: self.add_conditions())
        self.table.bind('<<TreeviewSelect>>', lambda event: self._update_buttons())

        bulk = ttk.Frame(content)
        bulk.pack(fill='x', pady=(10, 0))
        for model, name in self.models.items():
            ttk.Label(bulk, text=f'{name}:').pack(side='left', padx=(0, 4))
            ttk.Button(bulk, text='All', width=5, command=lambda m=model: self.set_all(m, True)).pack(side='left', padx=(0, 2))
