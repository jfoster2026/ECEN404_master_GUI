    def _table_tab(self, tabs, name):
        frame = ttk.Frame(tabs, padding=(0, 8, 0, 0))
        tabs.add(frame, text=name)
        frame.rowconfigure(0, weight=1)
        frame.columnconfigure(0, weight=1)
        table = ttk.Treeview(frame, show='headings', style='Stats.Treeview')
        vertical = ttk.Scrollbar(frame, orient='vertical', command=table.yview)
        horizontal = ttk.Scrollbar(frame, orient='horizontal', command=table.xview)
        table.configure(yscrollcommand=vertical.set, xscrollcommand=horizontal.set)
        table.grid(row=0, column=0, sticky='nsew')
        vertical.grid(row=0, column=1, sticky='ns')
        horizontal.grid(row=1, column=0, sticky='ew')
        return table

    @staticmethod
    def _fill(table, frame, first_width=260):
        columns = [str(column) for column in frame.columns]
        table.delete(*table.get_children())
        table.configure(columns=columns)
        for index, column in enumerate(columns):
            table.heading(column, text=column)
            table.column(column, width=first_width if index == 0 else max(110, len(column)*9),
                         anchor='w' if index == 0 or column == 'Lowest NRMSE' else 'e', stretch=False)
        for row in frame.itertuples(index=False):
            table.insert('', 'end', values=[
                str(value) if index == 0 else _format(value) for index, value in enumerate(row)])

    def render(self):
        view = self.view.get()
        self.heading.configure(text=f'{len(self.tests)} tests · {VIEW_LABELS[view]}')
        shown = summary_table(self.data, view).drop(columns='column').rename(columns={'statistic': 'Statistic'})
        self._fill(self.summary, shown)
        self._fill(self.per_test, per_test_table(self.data, view), first_width=110)
        self.draw_sensitivity()
        self.draw_waveforms()

    def draw_sensitivity(self):
        """The input sensitivity window's plots for one model; always full-waveform NRMSE."""
        model = self.sensitivity_model.get()
        results = [self.results[model][shot] for shot in self.tests if shot in self.results[model]]
        if results:
            plotted = plot_sensitivity(self.sensitivity_axes, modeled_test_sensitivity(results))
            self.sensitivity_note.set(f'{model} · {len(results)} tests · {NRMSE_LABEL}'
                                      if plotted else f'{model}: no finite NRMSE values to plot.')
        else:
            for axis in self.sensitivity_axes:
                axis.clear()
            self.sensitivity_note.set(f'{model}: no stored test results.')
        self.sensitivity_figure.subplots_adjust(right=.80, hspace=.38, top=.95, bottom=.09)
        self.sensitivity_canvas.draw_idle()

    def draw_waveforms(self):
        view = self.view.get()
        shot = int(self.wave_test.get())
        figure = self.wave_figure
        figure.clear()
        figure.set_layout_engine('constrained')
        axis = figure.add_subplot()
        available = [model for model in self.models if shot in self.results[model]]
        if not available:
            axis.set_axis_off()
            axis.text(.5, .5, 'No stored waveforms for this test.', ha='center', transform=axis.transAxes)
            self.wave_canvas.draw_idle()
            return
        wave = self.results[available[0]][shot]['wave']
        time = wave.time_ns.to_numpy(float)
        window = window_mask(time, view)
        axis.plot(time, wave.actual_v, color=MEASURED_COLOR, linewidth=2.0, label='Measured')
        values = [wave.actual_v.to_numpy(float)[window]]
        for model in available:
            result = self.results[model][shot]
            predicted = np.asarray(result['predicted'], float)
            nrmse = result['evaluations'][view]['nrmse_pct']
            axis.plot(time, predicted, color=self.colors[model], linestyle=self.dashes[model], linewidth=1.8,
                      label=f'{model} (NRMSE {_format(nrmse)} %)')
            values.append(predicted[window])
        if view in WINDOWS:
            axis.set_xlim(*WINDOWS[view])
        values = np.concatenate(values)
        values = values[np.isfinite(values)]
        if values.size:
            margin = max(float(np.ptp(values))*.08, .01)
            axis.set_ylim(values.min()-margin, values.max()+margin)
        axis.set_xlabel('Time (ns)')
        axis.set_ylabel('Diode output (V)')
        axis.set_title(f'Test {shot} · {VIEW_LABELS[view]} · held-out predictions', fontsize=10)
        axis.grid(alpha=.25)
        axis.legend(loc='upper right', fontsize=8)
        self.wave_canvas.draw_idle()

    def toggle_fullscreen(self, enabled=None):
        if enabled is None:
            enabled = not self.attributes('-fullscreen')
        self.attributes('-fullscreen', bool(enabled))
        self.fullscreen_button.configure(text='Exit full screen' if enabled else 'Full screen')

    def save_csv(self):
        path = filedialog.asksaveasfilename(parent=self, title='Download model comparison',
                                            defaultextension='.csv', filetypes=[('CSV files', '*.csv')],
                                            initialfile='model_comparison.csv')
        if path:
            try:
                export_table(self.data).to_csv(path, index=False, na_rep='', encoding='utf-8-sig')
            except OSError as error:
                messagebox.showerror('Unable to save comparison', str(error), parent=self)


