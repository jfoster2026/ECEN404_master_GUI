    def save_all_stats(self, data=None, parent=None, view=None):
        data = self.batch_stats if data is None else data
        if data is None:
            return
        view = self.batch_stats_view if view is None else view
        parent = self.root if parent is None else parent
        path = filedialog.asksaveasfilename(parent=parent, title=f'Download {view} waveform stats',
                                          defaultextension='.csv', filetypes=[('CSV files', '*.csv')],
                                          initialfile=f"{data.attrs.get('model_slug', 'all_tests')}_{view}_waveform_stats.csv")
        if path:
            try:
                export = batch_report(data, view)
                export.insert(0, 'window', view)
                if data.attrs.get('model_name'):
                    export.insert(0, 'model', data.attrs['model_name'])
                export.to_csv(path, index=False, na_rep='N/A', encoding='utf-8-sig')
                self.status.set(f'Saved {view} waveform stats for {len(data)} tests.')
            except OSError as error:
                messagebox.showerror('Unable to save waveform stats', str(error), parent=parent)

