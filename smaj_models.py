def sweep_values(feature, conditions, shot_id, *, include_baseline=True):
    """Choose realistic values from the available conditions and include baseline."""
    if feature not in FEATURES:
        raise ValueError(f'Unknown input sensitivity variable: {feature}')
    selected = conditions.loc[conditions.shot_id.eq(int(shot_id))]
    if len(selected) != 1:
        raise ValueError(f'Test {shot_id} must match exactly one input condition.')
    baseline = float(selected.iloc[0][feature])
    values = np.asarray(conditions[feature], dtype=float)
    values = values[np.isfinite(values)]
    if not len(values):
        raise ValueError(f'No finite values for {FEATURES[feature]}.')
    low, high = float(values.min()), float(values.max())
    if feature == 'dose_rate' and low > 0:
        grid = np.geomspace(low, high, 9) if low < high else np.array([low])
    elif feature == 'load_ohm':
        grid = np.quantile(values, np.linspace(0, 1, min(9, len(np.unique(values)))))
        threshold = 1e5  # This is a model input boundary: load_ohm >= 100 kΩ.
        if low < threshold < high:
            grid = np.r_[grid, np.nextafter(threshold, 0.), threshold]
    else:
        grid = np.linspace(low, high, 9) if low < high else np.array([low])
    return np.unique(np.r_[grid, baseline]) if include_baseline else np.unique(grid)


def profile_sweep(*, result, conditions, shot_id, feature, time_ns, baseline_prediction,
                  predict, progress=None, values=None):
    """Run paired one-feature counterfactuals with the fitted model held fixed."""
    if feature not in FEATURES:
        raise ValueError(f'Unknown input sensitivity variable: {feature}')
    selected = conditions.loc[conditions.shot_id.eq(int(shot_id))]
    if len(selected) != 1:
        raise ValueError(f'Test {shot_id} must match exactly one input condition.')
    baseline_value = float(selected.iloc[0][feature])
    grid = sweep_values(feature, conditions, shot_id) if values is None else np.asarray(values, dtype=float)
    time = np.asarray(time_ns, dtype=float)
    baseline = np.asarray(baseline_prediction, dtype=float)
    values, curves, summaries = [], [], []
    report = progress or (lambda text: None)
    for index, value in enumerate(grid, 1):
        report(f'Sweeping {FEATURES[feature]} {index}/{len(grid)}...')
        scenario = selected.copy()
        scenario.loc[:, feature] = value
        curve = baseline.copy() if value == baseline_value else np.asarray(predict(scenario), dtype=float)
        if curve.shape != baseline.shape:
            raise ValueError('Every sensitivity prediction must match the baseline waveform shape.')
        values.append(float(value))
        curves.append(curve)
        summaries.append(response_summary(result, curve))
    return dict(feature=feature, feature_label=FEATURES[feature], baseline_value=baseline_value,
                values=values, waveforms=curves, summaries=summaries, time_ns=time.tolist())


def aggregate_sweeps(results, feature, analyze, *, progress=None):
    """Summarize each input value's effect on reported waveform statistics."""
    results = list(results)
    if not results:
        raise ValueError('Run all tests before calculating input sensitivity.')
    conditions = results[0]['conditions']
    values = sweep_values(feature, conditions, int(conditions.iloc[0].shot_id),
                          include_baseline=False)
    report = progress or (lambda text: None)
    per_test = []
    for index, result in enumerate(results, 1):
        report(f'Sweeping {FEATURES[feature]} for test {result["shot_id"]} ({index}/{len(results)})...')
        analyzed = analyze(result, feature, values=values)
        analyzed['shot_id'] = int(result['shot_id'])
        selected = result['conditions'].loc[
            result['conditions'].shot_id.eq(int(result['shot_id']))]
        if len(selected) != 1:
            raise ValueError(f'Test {result["shot_id"]} must match exactly one input condition.')
        analyzed['load_ohm'] = float(selected.iloc[0]['load_ohm'])
        per_test.append(analyzed)
    summaries = []
    points = []
    for value_index, _value in enumerate(values):
        rows = [item['summaries'][value_index] for item in per_test]
        statistics = {}
        nrmse = np.asarray([row['nrmse_pct'] for row in rows], dtype=float)
        finite = nrmse[np.isfinite(nrmse)]
        statistics['nrmse_mean_pct'] = float(np.mean(finite)) if len(finite) else np.nan
        statistics['nrmse_count'] = len(finite)
        for item, row in zip(per_test, rows):
            baseline = item['baseline_value']
            change_pct = (100 * (_value - baseline) / abs(baseline)
                          if np.isfinite(baseline) and baseline != 0 else np.nan)
            points.append(dict(value=float(_value), baseline_value=baseline,
                               change_pct=float(change_pct), nrmse_pct=row['nrmse_pct'],
                               shot_id=int(item['shot_id']), load_ohm=item['load_ohm']))
        summaries.append(dict(statistics=statistics, test_count=len(rows)))
    return dict(feature=feature, feature_label=FEATURES[feature], values=values.tolist(),
                summaries=summaries, tests_run=len(per_test),
                shot_ids=[int(result['shot_id']) for result in results],
                points=points)


def modeled_test_sensitivity(results, features=None, *, progress=None):
    """Collect scores and inputs from existing held-out predictions only."""
    results = list(results)
    if not results:
        raise ValueError('Run all tests before plotting modeled-test results.')
    features = SENSITIVITY_FEATURES if features is None else features
    report = progress or (lambda text: None)
    points_by_feature = {feature: [] for feature in features}
    for index, result in enumerate(results, 1):
        shot_id = int(result['shot_id'])
        report(f'Collecting existing model result for test {shot_id} ({index}/{len(results)})...')
        condition = result['conditions'].loc[result['conditions'].shot_id.eq(shot_id)]
        if len(condition) != 1:
            raise ValueError(f'Test {shot_id} must match exactly one input condition.')
        condition = condition.iloc[0]
        load = float(condition['load_ohm'])
        evaluation = result.get('evaluations', {}).get('full', {})
        nrmse = float(evaluation.get('nrmse_pct', np.nan))
        for feature in features:
            if feature not in FEATURES:
                raise ValueError(f'Unknown input sensitivity variable: {feature}')
            points_by_feature[feature].append(dict(
                value=float(condition[feature]), nrmse_pct=nrmse,
                shot_id=shot_id, load_ohm=load))

    output = {}
    for feature, points in points_by_feature.items():
        values = sorted({point['value'] for point in points})
        summaries = []
        for value in values:
            matching = [point['nrmse_pct'] for point in points
                        if point['value'] == value and np.isfinite(point['nrmse_pct'])]
            summaries.append(dict(value=value, test_count=len(matching), statistics=dict(
                nrmse_mean_pct=float(np.mean(matching)) if matching else np.nan,
                nrmse_count=len(matching))))
        output[feature] = dict(
            feature=feature, feature_label=FEATURES[feature], values=values,
            summaries=summaries, tests_run=len(results),
            shot_ids=[int(result['shot_id']) for result in results], points=points)
    return output


def response_summary(result, prediction):
    """Return full-waveform NRMSE (%) against the measured held-out waveform."""
    time = result['wave'].time_ns.to_numpy(float)
    actual = result['wave'].actual_v.to_numpy(float)
    predicted = np.asarray(prediction, dtype=float)
    if predicted.shape != actual.shape:
        raise ValueError('Sensitivity prediction must match the measured waveform shape.')
    valid = window_mask(time, 'full') & np.isfinite(actual) & np.isfinite(predicted)
    if valid.sum() < 5:
        return {'nrmse_pct': np.nan}
    rmse = float(np.sqrt(np.mean((actual[valid] - predicted[valid])**2)))
    reference = peak_magnitude(time, actual, 'full', valid)
    return {'nrmse_pct': normalized_percent(rmse, reference)}


