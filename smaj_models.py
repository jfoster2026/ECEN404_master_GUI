        actual = wave.actual_v.to_numpy(float)
        result['score'] = _metrics(actual, result['predicted'], (time >= -60) & (time <= 1000))
        result['full'] = _metrics(actual, result['predicted'])
        result.update(model_name=self.name, model_slug=self.slug)
        return add_evaluation(result)

