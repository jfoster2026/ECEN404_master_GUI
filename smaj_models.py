CONDITIONS = {'dose_rate': 'Dose rate (rad/s)', 'bias_v': 'Bias (V)', 'load_ohm': 'Load (Ω)',
              'pcd_fwhm_ns': 'PCD width (ns)', 'scope_scale_factor': 'Scope scale factor'}
MINIMUM_TESTS = 4


@dataclass
class TestEntry:
    shot_id: int | None
    source: str
    file: Path | None
    row: dict | None = None
    problem: str = ''

    @property
    def usable(self):
        return self.row is not None and not self.problem

    @property
    def status(self):
        if self.problem:
            return self.problem
        return 'Ready' if self.row is not None else 'Needs conditions'


def _resolve(base, value):
    if pd.isna(value) or not str(value).strip():
        return None
    return (base / Path(str(value).strip()).expanduser()).resolve()


def _waveform_problem(path):
    if path is None:
        return 'No waveform_csv path'
    if not path.is_file():
        return f'Waveform file not found: {path.name}'
    try:
        header = set(pd.read_csv(path, nrows=0).columns)
    except (OSError, ValueError) as error:
        return f'Unreadable CSV: {error}'
    if not ({'time_ns', 'actual_v'} <= header or {'Diode', 'PCD3_B'} <= header):
        return 'CSV needs time_ns/actual_v or Diode/PCD3_B columns'
    return ''


def condition_problem(values):
    """Return why a row of test conditions is invalid, or '' when it is usable."""
    for name in ('shot_id', *CONDITIONS, 'cached_scope_scale_factor'):
        try:
            value = float(values.get(name))
        except (TypeError, ValueError):
            value = np.nan
        if not np.isfinite(value):
            return f'{name} must be a number'
        if name != 'bias_v' and value <= 0:
            return f'{name} must be positive'
    if float(values['shot_id']) != int(float(values['shot_id'])):
        return 'shot_id must be an integer'
    return ''


class TestLibrary:
    def __init__(self, metadata=BUILTIN_METADATA, state_dir=STATE_DIR, default_folder=DEFAULT_FOLDER):
        self.metadata = Path(metadata)
        self.state_dir = Path(state_dir)
        self.default_folder = Path(default_folder)
        self.folder = self.default_folder
        self.excluded = {}
        state = self.state_dir / 'test_selection.json'
        if state.is_file():
            try:
                saved = json.loads(state.read_text(encoding='utf-8'))
                self.folder = Path(saved.get('folder') or self.default_folder)
                self.excluded = {model: {int(shot) for shot in shots}
                                 for model, shots in saved.get('excluded', {}).items()}
            except (OSError, ValueError, TypeError, AttributeError):
                pass  # A damaged selection file falls back to using every test.

    @property
    def new_metadata(self):
        return self.folder / NEW_METADATA_NAME

    def excluded_for(self, model):
        return set(self.excluded.get(model, set()))

    def save(self):
        self.state_dir.mkdir(parents=True, exist_ok=True)
        folder = None if self.folder.resolve() == self.default_folder.resolve() else str(self.folder)
        state = dict(folder=folder, excluded={model: sorted(shots) for model, shots in self.excluded.items()})
        (self.state_dir / 'test_selection.json').write_text(json.dumps(state, indent=2), encoding='utf-8')

    def ensure_folder(self):
        """Create the drop-in folder and an empty metadata template the user can fill."""
        self.folder.mkdir(parents=True, exist_ok=True)
        if not self.new_metadata.exists():
            pd.DataFrame(columns=COLUMNS).to_csv(self.new_metadata, index=False)
        return self.folder

    def scan(self):
        """List every SMAJ400A test with whether it can be offered to the models."""
        entries = []
        builtin = pd.read_csv(self.metadata)
        for row in builtin.to_dict('records'):
            if str(row.get('diode_type', '')).strip() != DIODE:
                continue
            path = _resolve(self.metadata.parent, row.get('waveform_csv'))
            row.update(waveform_csv=str(path) if path else '', diode_type=DIODE)
            row['shot_id'] = int(row['shot_id'])
            entries.append(TestEntry(row['shot_id'], 'Built-in', path, row, _waveform_problem(path)))
        if not self.folder.is_dir():
            return entries
        listed = set()
        if self.new_metadata.is_file():
            entries.extend(self._scan_new_metadata(listed))
        for path in sorted(self.folder.glob('*.csv')):
            path = path.resolve()
            if path == self.new_metadata.resolve() or path in listed:
                continue
            digits = re.findall(r'\d+', path.stem)
            entries.append(TestEntry(int(digits[0]) if digits else None, 'New folder', path,
                                     problem=_waveform_problem(path)))
        used = {}
        for entry in entries:
            if entry.row is None or entry.problem:
                continue
            if entry.shot_id in used:
                entry.problem = f'Duplicate shot ID (also {used[entry.shot_id].lower()})'
            else:
                used[entry.shot_id] = entry.source
        return entries

    def _scan_new_metadata(self, listed):
        try:
            frame = pd.read_csv(self.new_metadata)
        except (OSError, ValueError) as error:
            return [TestEntry(None, 'New folder', self.new_metadata, problem=f'Unreadable metadata: {error}')]
        missing = {'shot_id', 'waveform_csv', *CONDITIONS} - set(frame.columns)
        if missing:
            return [TestEntry(None, 'New folder', self.new_metadata,
                              problem=f'{NEW_METADATA_NAME} is missing {", ".join(sorted(missing))}')]
        entries = []
        for row in frame.to_dict('records'):
            diode = row.get('diode_type')
            row['diode_type'] = DIODE if pd.isna(diode) or not str(diode).strip() else str(diode).strip()
            if row['diode_type'] != DIODE:
                continue
            if pd.isna(row.get('cached_scope_scale_factor')):
                row['cached_scope_scale_factor'] = row['scope_scale_factor']
            path = _resolve(self.folder, row['waveform_csv'])
            if path is not None:
                listed.add(path)
            problem = condition_problem(row) or _waveform_problem(path)
            shot = None if problem.startswith('shot_id') else int(float(row['shot_id']))
            row.update(shot_id=shot, waveform_csv=str(path) if path else '')
            entries.append(TestEntry(shot, 'New folder', path, row, problem))
        return entries

    def add_conditions(self, waveform, values):
        """Append a new test's conditions to the drop-in folder's metadata CSV."""
        row = dict(values, diode_type=DIODE)
        row.setdefault('cached_scope_scale_factor', row['scope_scale_factor'])
        problem = condition_problem(row)
        if problem:
            raise ValueError(problem)
        row['shot_id'] = int(float(row['shot_id']))
        taken = {entry.shot_id for entry in self.scan() if entry.row is not None}
        if row['shot_id'] in taken:
            raise ValueError(f'Shot ID {row["shot_id"]} is already used by another test.')
        waveform = Path(waveform).resolve()
        try:
            row['waveform_csv'] = waveform.relative_to(self.folder.resolve()).as_posix()
        except ValueError:
            row['waveform_csv'] = str(waveform)
        self.ensure_folder()
        frame = pd.read_csv(self.new_metadata)
        frame = pd.concat([frame, pd.DataFrame([row])], ignore_index=True)
        frame.to_csv(self.new_metadata, index=False, columns=[*COLUMNS, *(c for c in frame if c not in COLUMNS)])
        return row['shot_id']

    def write_metadata(self, model, entries=None):
        """Write the metadata CSV holding only the tests checked for this model."""
        entries = self.scan() if entries is None else entries
        excluded = self.excluded_for(model)
        rows = [entry.row for entry in entries if entry.usable and entry.shot_id not in excluded]
        frame = pd.DataFrame(rows)
        for column in COLUMNS:
            if column not in frame:
                frame[column] = pd.Series(dtype=object)
        # Only gain-mode research runs use attenuation; drop it rather than leave gaps.
        if 'scope_attenuation_setting' in frame and frame.scope_attenuation_setting.isna().any():
            frame = frame.drop(columns='scope_attenuation_setting')
        self.state_dir.mkdir(parents=True, exist_ok=True)
        path = self.state_dir / f'{model}_metadata.csv'
        frame.to_csv(path, index=False)
        return path


