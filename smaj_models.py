def siamese_fit_expanded(conditions, features, extra=False, balanced=False, gains=None):
    siamese_require_smaj(conditions)
    if len(conditions) < 3:
        raise ValueError("Need at least three training shots.")
    labels=features.set_index('shot_id').loc[conditions.shot_id]
    target=labels[list(SIAMESE_TARGETS)].to_numpy(float)
    focus=(SIAMESE_KNOTS_NS>=-60)&(SIAMESE_KNOTS_NS<=1000)
    t=SIAMESE_KNOTS_NS[focus]; weights=np.diff(np.r_[t[0],(t[:-1]+t[1:])/2,t[-1]])
    best=None
    gain_modes=(False,True) if gains is not None else (False,)
    for gain_mode in gain_modes:
      gain=gains if gain_mode else np.ones(len(conditions))
      y=target/gain[:,None]
      for kind in ['linear','rbf:0.5','rbf:1.0','rbf:2.0']+(['hybrid:0.5','hybrid:1.0','hybrid:2.0','regime:0.5','regime:1.0','regime:2.0'] if extra else []):
        k=siamese_kernel(conditions,conditions,kind)
        for alpha in (.01,.1,1.,10.):
            groups,errors=_siamese_solve(k,y,alpha)
            errors=errors*gain[:,None]
            available=np.isfinite(errors[:,focus]);denom=(available*weights).sum(axis=1)
            error=np.sqrt(np.nansum(errors[:,focus]**2*weights,axis=1)/np.maximum(denom,1e-12))
            score=error[denom>0].mean()
            if balanced:
                tail=SIAMESE_KNOTS_NS>=0;times=SIAMESE_KNOTS_NS[tail]
                tw=np.diff(np.r_[times[0],(times[:-1]+times[1:])/2,times[-1]])
                avail=np.isfinite(errors[:,tail]);td=(avail*tw).sum(axis=1)
                terr=np.sqrt(np.nansum(errors[:,tail]**2*tw,axis=1)/np.maximum(td,1e-12))
                score=.5*(score+terr[td>0].mean())
            if best is None or score<best['inner_score']:
                best=dict(kernel=kind,alpha=alpha,groups=groups,conditions=conditions.reset_index(drop=True).copy(),inner_score=score,gain_mode=gain_mode)
    return best


def siamese_kernel(left,right,kind):
    # Keep filtering/audit metadata outside the predictive kernel interface.
    predictors = list(SIAMESE_PREDICTOR_COLUMNS)
    return _siamese_kernel(left.loc[:, predictors], right.loc[:, predictors], kind)


def siamese_configure_knots(spacing=10, coarse_tail=False):
    """Reset the experiment grid so successive runs do not accumulate knots."""
    global SIAMESE_KNOTS_NS, SIAMESE_TARGETS
    if not np.isfinite(spacing) or spacing <= 0:
        raise ValueError('Knot spacing must be positive.')
    SIAMESE_KNOTS_NS = np.unique(np.r_[SIAMESE_BASE_KNOTS_NS, np.arange(-60, 1001, spacing),
                              [] if coarse_tail else np.arange(1000, 5001, 25)])
    SIAMESE_TARGETS = {f'dense_{i:03d}_v': 'identity' for i in range(len(SIAMESE_KNOTS_NS))}


def siamese_load_smaj_conditions(metadata=None):
    """Reload the editable metadata; cached result metadata is not consulted."""
    return read_metadata(metadata if metadata is not None else SIAMESE_ROOT/'simease_ridge_metadata.csv')


def siamese_read_waveform(row, raw_waveforms=False):
    return load_waveform(row, raw_waveforms)


def siamese_waveform_features(wave, shot_id, peak_v=None):
    good = wave.actual_v.notna()
    time, voltage = wave.time_ns.to_numpy()[good], wave.actual_v.to_numpy()[good]
    smooth = gaussian_filter1d(voltage, 1.5/2)
    if peak_v is None:
        peak_v = siamese_waveform_parameters(time, smooth)['peak_v']
    values = np.interp(SIAMESE_KNOTS_NS, time, smooth, left=np.nan, right=np.nan)
    return dict(shot_id=shot_id, peak_v=peak_v, **dict(zip(SIAMESE_TARGETS, values)))


def fit_holdout(shot_id, *, raw_waveforms=False, progress=None, metadata=None, read=None):
    """Fit one held-out test and return its training-only inference state.

    read(row) may supply cached waveforms; it defaults to read_waveform.
    """
    report = progress if progress is not None else lambda message: None
    read = read if read is not None else lambda row: siamese_read_waveform(row, raw_waveforms)
    conditions = siamese_load_smaj_conditions(metadata)
    test = conditions.loc[conditions.shot_id.eq(shot_id)]
    if len(test) != 1:
        raise ValueError(f'Test {shot_id} is not an available SMAJ400A test.')
    train = conditions.loc[conditions.shot_id.ne(shot_id)].reset_index(drop=True)
    siamese_configure_knots(10, coarse_tail=True)
    features = []
    for index, row in enumerate(train.itertuples(), 1):
        report(f'Loading training test {row.shot_id} ({index}/{len(train)})...')
        wave = read(row)
        features.append(siamese_waveform_features(wave, row.shot_id))
    report(f'Fitting on {len(train)} SMAJ400A tests; test {shot_id} is held out...')
    fitted = siamese_fit_expanded(train, pd.DataFrame(features), extra=True)
    return conditions, test, train, fitted


def siamese_model_shot(shot_id, *, raw_waveforms=False, progress=None, metadata=None, prediction_factory=None,
               read=None):
    """Fit and predict one holdout, reading its voltage only after inference.

    The combined GUI supplies a prediction_factory for profiled PyTorch inference
    and a cached read(row); the default path retains NumPy/SciPy prediction,
    reads files directly and needs no PyTorch import.
    """
    report = progress if progress is not None else lambda message: None
    read = read if read is not None else lambda row: siamese_read_waveform(row, raw_waveforms)
    conditions, test, train, fitted = fit_holdout(
        shot_id, raw_waveforms=raw_waveforms, progress=report, metadata=metadata, read=read)
    if prediction_factory is None:
        parameters = siamese_predict(fitted, test).iloc[0].to_dict()
    else:
        prediction = prediction_factory(fitted, test, SIAMESE_KNOTS_NS)
    report(f'Comparing the prediction with test {shot_id}...')
    row = next(test.itertuples())
    wave = read(row)
    time = wave.time_ns.to_numpy()
    predicted = (siamese_reconstruct(time, parameters) if prediction_factory is None
                 else prediction.waveform(time))
    score = _siamese_metrics(wave.actual_v.to_numpy(), predicted, (time >= -60) & (time <= 1000))
    full = _siamese_metrics(wave.actual_v.to_numpy(), predicted)
    return dict(shot_id=int(shot_id), diode_type=SIAMESE_TRAINING_DIODE, wave=wave[['time_ns', 'actual_v']].copy(),
                predicted=predicted, score=score, full=full, train_shot_ids=train.shot_id.tolist(),
                kernel=fitted['kernel'], alpha=fitted['alpha'], conditions=conditions,
                **({} if prediction_factory is None else {'compute_cost': prediction.compute_cost}),
                **({} if prediction_factory is None else {'_sensitivity_context': {
                    'kind': 'ridge', 'model': fitted, 'knots': SIAMESE_KNOTS_NS.copy()}}),
                compute_structure=dict(training_tests=len(train), kernel=fitted['kernel'],
                    coefficient_shapes=[group['coefficient'].shape for group in fitted['groups']]))


def siamese_run(spacing=10, extra=False, balanced=False, gain=False, coarse_tail=False, raw_waveforms=False, metadata=None):
    if spacing <= 0:
        raise ValueError('Knot spacing must be positive.')
    name='dense_'+str(spacing)+'ns'+('_hybrid' if extra else '')+('_balanced' if balanced else '')+('_gain' if gain else '')+('_coarse_tail' if coarse_tail else '')+('_documented' if '--documented' in sys.argv else '')
    name += '_smaj400a'
    output_dir=SIAMESE_ROOT/'research'/f'{name}_waveforms'
    output_dir.mkdir(parents=True, exist_ok=True)
    c = siamese_load_smaj_conditions(metadata)
    print(f'Using {len(c)} SMAJ400A shots from {metadata or SIAMESE_ROOT/"simease_ridge_metadata.csv"}.', flush=True)
    if gain and 'scope_attenuation_setting' not in c:
        raise ValueError('--gain requires scope_attenuation_setting in the metadata CSV.')
    c.to_csv(output_dir/'conditions_used.csv', index=False)
    siamese_configure_knots(spacing, coarse_tail)
    f=[]; waves={}
    for row in c.itertuples():
        w = siamese_read_waveform(row, raw_waveforms)
        waves[row.shot_id]=w
        f.append(siamese_waveform_features(w, row.shot_id))
        print(f'Loaded shot {row.shot_id} ({len(f)}/{len(c)})', flush=True)
    f=pd.DataFrame(f); rows=[]
    for row in c.itertuples():
        train=c[c.shot_id!=row.shot_id]; test=c[c.shot_id==row.shot_id]
        fitted=siamese_fit_expanded(train,f,extra,balanced,train.scope_attenuation_setting.to_numpy() if gain else None) if extra else siamese_fit_model(train,f)
        params=siamese_predict(fitted,test).iloc[0].to_dict()
        if fitted.get('gain_mode'): params.update({name:params[name]*float(test.scope_attenuation_setting.iloc[0]) for name in SIAMESE_TARGETS})
        w=waves[row.shot_id]; pred=siamese_reconstruct(w.time_ns.to_numpy(),params)
        score=_siamese_metrics(w.actual_v.to_numpy(),pred,SIAMESE_PROMPT)
        full=_siamese_metrics(w.actual_v.to_numpy(),pred)
        siamese_plot_waveform(w,pred,row.shot_id,row.diode_type,score,full,output_dir)
        pd.DataFrame(dict(time_ns=w.time_ns,actual_v=w.actual_v,predicted_v=pred)).to_csv(output_dir/f'{row.shot_id}_waveform.csv',index=False)
        rows.append(dict(shot_id=row.shot_id,diode_type=row.diode_type,**score,full_rmse_v=full['rmse_v'],kernel=fitted['kernel'],alpha=fitted['alpha'],gain_mode=fitted.get('gain_mode',False),n_train=len(train),train_shot_ids=';'.join(map(str, train.shot_id))))
        print(row.shot_id,score['rmse_v'],flush=True)
    result=pd.DataFrame(rows)
    result.to_csv(SIAMESE_ROOT/'research'/f'{name}.csv',index=False)
    result.to_csv(output_dir/'metrics.csv',index=False)
    cards = []
    for diode_type, shots in result.groupby('diode_type', sort=True):
        cards.append(f'<h2>{escape(diode_type)}</h2><div class="grid">')
        for shot in shots.itertuples():
            filename = f'{shot.shot_id}_predicted_vs_actual.png'
            cards.append(
                f'<figure><a href="{filename}"><img src="{filename}" loading="lazy" '
                f'alt="Shot {shot.shot_id}: predicted and actual waveform"></a>'
                f'<figcaption>Shot {shot.shot_id} | Prompt RMSE: {shot.rmse_v:.3f} V'
                f'</figcaption></figure>')
        cards.append('</div>')
    (output_dir/'index.html').write_text(
        '<!doctype html><html lang="en"><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width, initial-scale=1">'
        '<title>Diode waveform predictions</title><style>'
        'body{font-family:system-ui;margin:2rem;background:#f4f6f8;color:#172330}'
        '.grid{display:grid;grid-template-columns:repeat(auto-fit,minmax(min(100%,480px),1fr));gap:1rem}'
        'figure{margin:0;padding:1rem;background:white;border-radius:8px}'
        'img{width:100%;height:auto}figcaption{padding-top:.5rem}'
        '</style><h1>Diode waveform predictions</h1>'
        f'<p>{len(result)} SMAJ400A-only leave-one-shot-out predictions. Training and inner model selection use SMAJ400A shots only. Click an image to view full size.</p>'
        '<p><a href="metrics.csv">Download metrics</a></p>'
        + ''.join(cards) + '</html>', encoding='utf-8')
    print(f'Saved {len(result)} waveform PNGs and prediction CSVs to {output_dir}',flush=True)
    print(result.groupby('diode_type')[['rmse_v','full_rmse_v']].mean().to_string())
    print(result[['rmse_v','full_rmse_v']].mean().to_string())


