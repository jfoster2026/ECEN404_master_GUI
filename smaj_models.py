# torch_model_inference.py
# ============================================================================
#
# Float64 CPU inference for the combined GUI, profiled by PyTorch itself.
#
# Only the built-in FlopCounterMode formulas are used. Unregistered operations
# (including most elementwise/special functions) can contribute zero FLOPs.
# Tensor conversion, training, diagnostics and scoring are outside the contexts.
# Parameter prediction and waveform reconstruction are counted separately and
# summed, so no measurement I/O needs to run inside a profiling context.
#
# Renamed in the bundle: PREDICTOR_COLUMNS -> TORCH_PREDICTOR_COLUMNS, encode -> torch_encode, kernel -> torch_kernel

from collections import Counter

import numpy as np

try:
    import torch
    from torch.utils.flop_counter import FlopCounterMode
except ImportError as error:
    raise ImportError(
        'The combined GUI needs PyTorch. Install with '
        'python -m pip install -r requirements-smaj.txt in its environment.'
    ) from error


TORCH_PREDICTOR_COLUMNS = ('dose_rate', 'bias_v', 'load_ohm', 'pcd_fwhm_ns')
LOG_COLUMNS = (3, 5, 6, 8, 9)


def tensor(values):
    # pandas may expose read-only arrays. Own the storage before creating a CPU tensor.
    return torch.from_numpy(np.array(values, dtype=np.float64, copy=True))


def torch_encode(values):
    dose = torch.log10(values[:, 0]/1e10)
    bias = values[:, 1]/5.25
    high = (values[:, 2] >= 1e5).to(torch.float64)
    low = (1-high)*(values[:, 2]/81.3-1)
    width = values[:, 3]/40-1
    return torch.stack((dose, bias, high, low, width, dose*bias,
                        dose*high, bias*high, dose*low), dim=1)


def torch_kernel(x, y, kind):
    if kind == 'linear':
        return 1+2*(x@y.T)
    name, length_text = kind.split(':')
    length = float(length_text)
    if name not in ('rbf', 'hybrid', 'regime') or not np.isfinite(length) or length <= 0:
        raise ValueError(f'Unsupported condition kernel: {kind}')
    weights = x.new_tensor([1, 2, 1.5, 2, 2])
    distance = (((x[:, None, :5]-y[None, :, :5])*weights)**2).sum(dim=2)
    covariance = torch.exp(-distance/(2*length**2))
    if name in ('hybrid', 'regime'):
        features = [0, 1, 2, 3, 5, 6, 7, 8] if name == 'hybrid' else [1, 2, 3, 7]
        covariance = covariance+x[:, features]@y[:, features].T
    return covariance


def _edge_slope(h0, h1, m0, m1):
    slope = ((2*h0+h1)*m0-h0*m1)/(h0+h1)
    wrong_sign = slope.sign() != m0.sign()
    limit = (m0.sign() != m1.sign()) & (slope.abs() > 3*m0.abs())
    return torch.where(wrong_sign, 0., torch.where(limit, 3*m0, slope))


def pchip(time, knots, values):
    """PCHIP slopes and cubic evaluation matching SciPy's real-valued algorithm."""
    h = torch.diff(knots)
    m = torch.diff(values)/h
    if len(knots) == 2:
        derivatives = torch.stack((m[0], m[0]))
    else:
        zero = (m[:-1] == 0) | (m[1:] == 0) | (m[:-1].sign() != m[1:].sign())
        safe_left = torch.where(zero, 1., m[:-1])
        safe_right = torch.where(zero, 1., m[1:])
        w1, w2 = 2*h[1:]+h[:-1], h[1:]+2*h[:-1]
        interior = torch.where(zero, 0., (w1+w2)/(w1/safe_left+w2/safe_right))
        derivatives = torch.cat((
            _edge_slope(h[0], h[1], m[0], m[1]).reshape(1), interior,
            _edge_slope(h[-1], h[-2], m[-1], m[-2]).reshape(1)))
    t = (derivatives[:-1]+derivatives[1:]-2*m)/h
    c0, c1 = t/h, (m-derivatives[:-1])/h-t
    clipped = time.clamp(knots[0], knots[-1])
    indices = (torch.searchsorted(knots, clipped, right=True)-1).clamp(0, len(knots)-2)
    dx = clipped-knots[indices]
    return ((c0[indices]*dx+c1[indices])*dx+derivatives[indices])*dx+values[indices]


def inverse_transform(values):
    result = values.clone()
    result[:2] = torch.sinh(result[:2].clamp(-12, 12))
    result[list(LOG_COLUMNS)] = torch.exp(result[list(LOG_COLUMNS)].clamp(-8, 12))
    lower = result.new_tensor([-100, .5, 0, 1, .1, 0, 10, .5])
    upper = result.new_tensor([150, 100, 1.5, 10000, 12, 1.5, 8000, 2000])
    result[2:] = result[2:].clamp(lower, upper)
    return result


def hill_waveform(time, parameters):
    baseline, amplitude, onset, width, recovery, half, n, drop, td, kd = parameters
    elapsed = (time-onset-4*width).clamp(min=0.)
    hill = torch.sigmoid(n*(torch.log(elapsed.clamp(min=1e-300))-torch.log(half)))
    sigmoid0 = torch.sigmoid(-td/kd)
    delayed_drop = (torch.sigmoid((elapsed-td)/kd)-sigmoid0)/(1-sigmoid0).clamp(min=1e-12)
    recovery_curve = amplitude*(1-recovery*hill+drop*delayed_drop)
    return baseline+torch.sigmoid((time-onset)/width)*recovery_curve


class _ProfiledPrediction:
    def __init__(self):
        self._counts = {}
        self._totals = {}
        self.prediction_samples = 0

    def _profile(self, stage, function, *args):
        with torch.no_grad(), FlopCounterMode(display=False) as counter:
            output = function(*args)
        self._totals[stage] = int(counter.get_total_flops())
        self._counts[stage] = {str(op): int(count)
                               for op, count in counter.get_flop_counts().get('Global', {}).items()}
        return output

    @property
    def compute_cost(self):
        counts = Counter()
        for stage in self._counts.values():
            counts.update(stage)
        return dict(inference_flops=int(sum(self._totals.values())),
                    compute_method='pytorch_flop_counter', torch_version=str(torch.__version__),
                    flops_by_operator=dict(counts),
                    regression_coefficients=self.regression_coefficients,
                    prediction_samples=self.prediction_samples)


class RidgePrediction(_ProfiledPrediction):
    def __init__(self, model, condition, knots):
        super().__init__()
        if len(condition) != 1:
            raise ValueError('Profile one held-out condition at a time.')
        self.knots = tensor(knots)
        self.kind = model['kernel']
        self.groups = [{key: (torch.as_tensor(value, dtype=torch.int64, device='cpu') if key in ('indices', 'columns')
                              else tensor(value)) for key, value in group.items()}
                       for group in model['groups']]
        self.regression_coefficients = sum(group['coefficient'].numel() for group in self.groups)
        query = tensor(condition.loc[:, list(TORCH_PREDICTOR_COLUMNS)].to_numpy(float))
        training = tensor(model['conditions'].loc[:, list(TORCH_PREDICTOR_COLUMNS)].to_numpy(float))
        self.values = self._profile('parameters', self._predict, query, training)
        if not torch.isfinite(self.values).all():
            raise ValueError('All predicted spline parameters must be finite.')

    def _predict(self, query, training):
        covariance = torch_kernel(torch_encode(query), torch_encode(training), self.kind)
        values = self.knots.new_empty(len(self.knots))
        for group in self.groups:
            k = covariance[:, group['indices']]
            centered = k-group['column_mean'][None, :]-k.mean(dim=1, keepdim=True)+group['grand_mean']
            values[group['columns']] = (centered@group['coefficient']+group['mean'])[0]
        return values

    def waveform(self, time):
        output = self._profile('waveform', pchip, tensor(time), self.knots, self.values)
        self.prediction_samples = len(time)
        return output.numpy()


class HillPrediction(_ProfiledPrediction):
    def __init__(self, posterior, condition):
        super().__init__()
        if len(condition) != 1:
            raise ValueError('Profile one held-out condition at a time.')
        self.posterior = posterior
        query = tensor(condition.loc[:, list(TORCH_PREDICTOR_COLUMNS)].to_numpy(float))
        fitted = {key: tensor(posterior[key]) for key in ('mean', 'covariance', 'center', 'scale')}
        self.regression_coefficients = fitted['mean'].numel()
        self.values, sd = self._profile('parameters', self._predict, fitted, query)
        self.parameters = self.values.numpy()
        self.sd = sd.numpy()

    @staticmethod
    def _predict(posterior, query):
        x = torch.cat((query.new_ones((1, 1)), torch_encode(query)), dim=1)
        mean = posterior['center']+(x@posterior['mean'])[0]*posterior['scale']
        variance = (x@posterior['covariance']@x.T)[0, 0]
        sd = torch.sqrt(variance.clamp(min=0.))*posterior['scale']
        return inverse_transform(mean), sd

    def waveform(self, time):
        output = self._profile('waveform', hill_waveform, tensor(time), self.values)
        self.prediction_samples = len(time)
        return output.numpy()


