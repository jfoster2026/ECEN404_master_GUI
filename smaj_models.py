# ============================================================================
# tabfm_launch.py
# ============================================================================
#
# Run the TabFM handoff's tabfm_smaj.py with a low-memory weight load.
#
# Usage (cwd = tabfm_handoff, with its .venv Python):
#     python -B ..\tabfm_launch.py run --data-dir ... --model-dir ... --device cpu --run-dir ...
#
# The vendored loader builds the float32 model (about 6.6 GB) and then
# memory-maps the whole 6.6 GB checkpoint with safetensors before casting to
# bfloat16. On Windows that mapping is charged against the commit limit, so the
# load needs about 13 GB free and fails ("paging file is too small") on a 16 GB
# laptop. This launcher replaces only safetensors.torch.load_model for the run:
# it reads the same file one tensor at a time with ordinary reads and copies each
# tensor into the same float32 parameter. The model then gets the identical values
# and the identical later bfloat16 cast, so predictions are unchanged; only the
# peak memory falls to about the model's own size. No handoff file is modified,
# so its hash checks and provenance still pass.
#
# Renamed in the bundle: main -> tabfm_launch_main

import json
from pathlib import Path
import runpy
import struct
import sys

DTYPES = {'F64': 'float64', 'F32': 'float32', 'F16': 'float16', 'BF16': 'bfloat16', 'I64': 'int64',
          'I32': 'int32', 'I16': 'int16', 'I8': 'int8', 'U8': 'uint8', 'BOOL': 'bool'}


def stream_load_model(model, filename, strict=True, device='cpu', **_):
    """safetensors.torch.load_model, reading one tensor at a time into the model's tensors."""
    import torch
    targets = model.state_dict()
    loaded = set()
    with open(filename, 'rb') as stream:
        (length,) = struct.unpack('<Q', stream.read(8))
        header = json.loads(stream.read(length))
        start = 8 + length
        unexpected = []
        for name, entry in sorted(((k, v) for k, v in header.items() if k != '__metadata__'),
                                  key=lambda item: item[1]['data_offsets'][0]):
            if name not in targets:
                unexpected.append(name)
                continue
            begin, end = entry['data_offsets']
            stream.seek(start + begin)
            buffer = bytearray(end - begin)
            stream.readinto(buffer)
            dtype = getattr(torch, DTYPES[entry['dtype']])
            tensor = torch.frombuffer(buffer, dtype=dtype) if buffer else torch.empty(0, dtype=dtype)
            tensor = tensor.reshape(entry['shape'])
            target = targets[name]
            if tuple(target.shape) != tuple(tensor.shape):
                raise RuntimeError(f'{name}: checkpoint shape {tuple(tensor.shape)} != model {tuple(target.shape)}')
            with torch.no_grad():
                target.copy_(tensor)
            loaded.add(name)
            del buffer, tensor
    # Tied tensors are stored once; a key sharing storage with a loaded one is loaded too.
    pointers = {targets[name].data_ptr() for name in loaded}
    missing = [name for name in targets if name not in loaded and targets[name].data_ptr() not in pointers]
    if strict and (missing or unexpected):
        raise RuntimeError(f'Checkpoint mismatch: missing {missing[:5]}, unexpected {unexpected[:5]}')
    if device not in (None, 'cpu'):
        model.to(device)
    return missing, unexpected


def tabfm_launch_main():
    try:
        import safetensors.torch
    except ImportError:  # The handoff environment always has it; stand-ins in tests may not.
        pass
    else:
        safetensors.torch.load_model = stream_load_model
    runner = Path.cwd() / 'tabfm_smaj.py'
    sys.path.insert(0, str(runner.parent))
    sys.argv = [str(runner), *sys.argv[1:]]
    runpy.run_path(str(runner), run_name='__main__')


if __name__ == '__main__':
    if len(sys.argv) < 2:
        raise SystemExit('Start the GUI with: python smaj_gui.py '
                         '(the GUI runs this file only as the TabFM launcher).')
    tabfm_launch_main()
    raise SystemExit(0)


# ============================================================================
# model_compute_cost.py
# ============================================================================
#
# Hardware-independent estimates for one full inference, excluding training.
#
# One scalar +, -, *, / counts as one arithmetic FLOP (a multiply-add is two).
# log/log10, exp, expit, sinh and sqrt count separately as nonlinear evaluations;
# their machine-dependent implementations are not assigned fabricated FLOP costs.
# These are algorithmic estimates, not hardware instructions or runtime rankings.
# Comparisons, allocation, I/O, scoring and diagnostic landmark extraction are
# excluded. See README_simease_ridge.md for the standalone Ridge accounting scope.
# The combined GUI uses torch_model_inference.py instead of these estimates.

def ridge_cost(model, samples):
    n = model['training_tests']
    kind = model['kernel'].split(':')[0]
    # Encode one query plus n training conditions: 12 arithmetic ops + log10 each.
    arithmetic = 12*(n+1)
    special = n+1
    if kind == 'linear':
        arithmetic += 19*n  # 9-term dot, then 1 + 2*dot.
    else:
        arithmetic += 20*n+2  # Five weighted squared distances; divide by 2*l*l.
        special += n  # exp of each squared distance.
        if kind == 'hybrid':
            arithmetic += 16*n  # Eight-term dot plus covariance addition.
        elif kind == 'regime':
            arithmetic += 8*n  # Four-term dot plus covariance addition.
    coefficients = 0
    knots = 0
    for rows, columns in model['coefficient_shapes']:
        coefficients += rows*columns
        knots += columns
        arithmetic += 4*rows + 2*rows*columns  # Center, dot, add output means.
    # PCHIP slope/Hermite setup estimate (upper branch count), then Horner
    # evaluation: time offset + three multiplies + three additions per sample.
    arithmetic += 24*knots-18 + 7*samples
    return dict(inference_flops_est=int(arithmetic), inference_special_evals=int(special),
                regression_coefficients=int(coefficients), prediction_samples=int(samples))


def hill_cost(samples, features=10, parameters=10):
    # Features include the intercept. Include the parameter uncertainty computed
    # by predict_parameters as well as its mean and inverse transforms.
    arithmetic = 12 + (2*features-1)*parameters + 2*parameters
    arithmetic += features*(2*features-1) + (2*features-1) + parameters
    # Hill/sigmoid/delayed-drop curve: 17 arithmetic ops/sample + four scalars.
    arithmetic += 17*samples+4
    # Encoding log10; uncertainty sqrt; inverse transforms (2 sinh, 5 exp);
    # waveform (log and 3 expit per sample; log(half) and sigmoid0 once).
    special = 4*samples+11
    return dict(inference_flops_est=int(arithmetic), inference_special_evals=int(special),
                regression_coefficients=features*parameters, prediction_samples=int(samples))


