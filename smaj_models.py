# tabfm_backend.py
# ============================================================================
#
# Tabular model (Google TabFM, in-context) from the team's TabFM handoff, for the combined SMAJ GUI.
#
# The handoff (tabfm_handoff/, the November 18 fresh-run package; see its
# README_TabFM_handoff.txt) owns the calculation and runs in its own Python
# environment (tabfm_handoff/.venv). One job is a background subprocess of
#
#     python -B tabfm_smaj.py run --data-dir data --model-dir <weights> --device cpu --run-dir results/<name>
#
# which prepares inputs, fits each of the 21 leave-one-test-out contexts and
# predicts the held-out test (folds/<test>/prediction.npz), then scores them. The
# runner is started through tabfm_launch.py, which only swaps in a low-memory
# (numerically identical) weight load so the 6.6 GB checkpoint fits in 16 GB RAM.
#
# - Protocol (unchanged): every fold's context is 64 sampled points from each of
#   the other 20 tests; TabFM's pretrained weights are never updated. The handoff
#   always runs the same fixed 21 SMAJ400A tests, so the GUI can only use it with
#   all 21 checked.
# - Coverage: TabFM predicts only from -100 to +400 ns around each test's raw
#   PCD 0.5 V crossing (about -120 to +380 ns on the GUI's time axis). The GUI
#   scores every window on the samples a model predicted, so the Tabular model's
#   Prompt-window and Full-waveform statistics cover only that span; First 200 ns
#   is fully covered.
# - Curves are TabFM's signed voltage (polarity x recorded diode volts) against
#   time from the computed PCD crossing. They are moved onto the GUI grid (time
#   from the PCD3_B peak) and divided by the scope scale factor, exactly as the
#   GUI's measured waveform is.
# - Cost is the handoff's PyTorch FLOP count for query inference (after the
#   context is encoded) times the 1000 predicted points; it excludes the context
#   fit, weight loading and preprocessing, as the other models exclude training.
# - Weights (~6.14 GiB, non-commercial license) live outside the repository in
#   %LOCALAPPDATA%\tabfm_model_weights, or TABFM_MODEL_DIR when set.
# - Completed runs stay in tabfm_handoff/results/ and are indexed in
#   tabfm_handoff/gui_jobs/ by a key over the test conditions, scope file contents,
#   handoff version and weights revision. Reopening the GUI reuses them.
#
# Renamed in the bundle: CACHE_VERSION -> TABFM_CACHE_VERSION, EXPERIMENT_FIELDS -> TABFM_EXPERIMENT_FIELDS, METADATA -> TABFM_METADATA, PACKAGE -> TABFM_PACKAGE, ROOT -> TABFM_ROOT

