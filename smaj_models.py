def handoff_experiments(package=TABFM_PACKAGE):
    """Enabled SMAJ400A rows of the handoff's experiment table, by integer test number."""
    path = Path(package) / 'experimental_setup' / 'experiments.csv'
    if not path.is_file():
        raise FileNotFoundError(f'The TabFM handoff is missing: {path}')
    table = pd.read_csv(path, dtype=str, keep_default_na=False)
    table = table.loc[table.enabled.str.strip().str.lower().eq('true') & table.diode.eq('SMAJ400A')].copy()
    table['test'] = table.shot_id.str.removeprefix('shot').astype(int)
    for field in TABFM_EXPERIMENT_FIELDS:
        table[field] = table[field].astype(float)
    return table.set_index('test', drop=False)


class TabularBackend:
    name = 'Tabular'
    slug = 'tabular'
    kind = 'tabfm'
    supports_input_sensitivity = True
    work_label = 'held-out tests need a TabFM prediction'
    minutes_per_item = 7.  # Measured: 21 folds in about 2.6 h on a 4-core laptop, one at a time.
    coverage_note = COVERAGE_NOTE
    description = ('A pretrained tabular foundation model (TabFM) predicts voltage from time, the PCD input '
                   'and the test conditions, using sampled points of the other 20 tests as its context. '
                   'It predicts only -100 to +400 ns around the PCD crossing.')

    def __init__(self, metadata=TABFM_METADATA, package=TABFM_PACKAGE, python=PYTHON, weights=WEIGHTS):
        self.metadata = Path(metadata)
        self.package = Path(package)
        self.jobs = self.package / 'gui_jobs'
        self.python = Path(python)
        self.weights = Path(weights)
        self._files = ScopeFileCache()
        self._index = None
        self._runs = {}
        self._process = None

    # Conditions and inputs -------------------------------------------------
    def load_smaj_conditions(self):
        conditions = load_smaj_conditions(self.metadata)
        return conditions.loc[conditions.shot_id.isin(handoff_experiments(self.package).index)].reset_index(drop=True)

    def clear_cache(self):
        self._files.clear()
        self._index = None
        self._runs = {}

    def stop(self):
        """End a running job (the GUI is closing); its partial output is never reused."""
        process, self._process = self._process, None
        if process is not None and process.poll() is None:
            if os.name == 'nt':
                subprocess.run(['taskkill', '/F', '/T', '/PID', str(process.pid)], capture_output=True,
                               creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0))
            else:
                process.terminate()

    def _inputs(self, conditions):
        experiments = handoff_experiments(self.package)
        rows = {int(row.shot_id): row for row in conditions.itertuples()}
        if set(rows) != set(experiments.index):
            missing = sorted(set(experiments.index) - set(rows))
            raise ValueError('The TabFM handoff always runs all 21 SMAJ400A tests together. '
                             f'Check test(s) {", ".join(map(str, missing))} for Tabular in Choose tests….')
        return rows, {shot: experiments.loc[shot] for shot in rows}

    def _identity(self, row, experiment):
        return dict(shot_id=experiment.shot_id, **{field: float(experiment[field]) for field in TABFM_EXPERIMENT_FIELDS},
                    data_sha256=self._files.get('digest', row, lambda row: digest_file(row.waveform_csv)))

    def _key(self, rows, experiments):
        version = {name: sha256((self.package / name).read_bytes()).hexdigest()
                   for name in ('FRESH_RUN_MANIFEST.json', 'MODEL_DOWNLOAD_MANIFEST.json', 'tabfm_smaj.py')}
        tests = sorted(json.dumps(self._identity(rows[shot], experiments[shot]), sort_keys=True) for shot in rows)
        text = json.dumps(dict(version=TABFM_CACHE_VERSION, handoff=version, settings=SETTINGS, tests=tests),
                          sort_keys=True, default=str)
        return sha256(text.encode()).hexdigest()

    def _stage(self, rows):
        """Copy each scope file into the handoff's data folder under the name it expects."""
        folder = self.package / 'data'
        folder.mkdir(exist_ok=True)
        for shot, row in rows.items():
            target = folder / f'LFXR_Lovejoy_Sept2021_{shot}.csv'
            wanted = self._files.get('digest', row, lambda row: digest_file(row.waveform_csv))
            if not target.is_file() or digest_file(target) != wanted:
                partial = target.with_suffix('.tmp')
                shutil.copyfile(row.waveform_csv, partial)
                partial.replace(target)

    # Job cache -------------------------------------------------------------
    @staticmethod
    def _finished(folder):
        return (folder / 'FROZEN.json').is_file() and (folder / 'evaluation' / 'metrics_full_precision.csv').is_file()

    def _completed(self):
        if self._index is None:
            self._index = {}
            for keys in sorted(self.jobs.glob(f'gui_{self.kind}_*.keys.json')):
                folder = self.package / 'results' / keys.name.removesuffix('.keys.json')
                if self._finished(folder):
                    for key in json.loads(keys.read_text(encoding='utf-8')):
                        self._index[key] = folder
        return self._index

    def missing_work(self, progress=None):
        (progress or (lambda text: None))('Checking the saved TabFM study...')
        rows, experiments = self._inputs(self.load_smaj_conditions())
        return (0 if self._key(rows, experiments) in self._completed() else len(rows)), len(rows)

    def _run_job(self, key, total, progress):
        if not self.python.is_file():
            raise FileNotFoundError('The TabFM environment is missing. See README_smaj_model_gui.md '
                                    '("Tabular model") to create tabfm_handoff\\.venv.')
        if not (self.weights / 'regression' / 'model.safetensors').is_file():
            raise FileNotFoundError(f'The TabFM weights are missing from {self.weights}. Download them with '
                                    'tabfm_handoff\\.venv\\Scripts\\python.exe -B -m handoff_tools.download_model '
                                    f'--destination "{self.weights}" (run inside tabfm_handoff).')
        self.jobs.mkdir(parents=True, exist_ok=True)
        stamp = time.strftime('%Y%m%d_%H%M%S')
        number = 1
        while (self.package / 'results' / f'gui_{self.kind}_{stamp}_{number}').exists() \
                or any(self.jobs.glob(f'gui_{self.kind}_{stamp}_{number}.*')):
            number += 1
        name = f'gui_{self.kind}_{stamp}_{number}'
        folder = self.package / 'results' / name
        # tabfm_launch.py runs the unchanged tabfm_smaj.py with a low-memory weight load.
        command = [str(self.python), '-B', str(LAUNCHER), 'run', '--data-dir', str(self.package / 'data'),
                   '--model-dir', str(self.weights), '--device', SETTINGS['device'], '--run-dir', str(folder)]
        log = self.jobs / f'{name}.log'
        started = time.monotonic()
        with log.open('x', encoding='utf-8') as stream:
            environment = dict(os.environ, PYTHONUTF8='1', PYTHONIOENCODING='utf-8')
            self._process = subprocess.Popen(command, cwd=self.package, stdout=stream, stderr=subprocess.STDOUT,
                                             env=environment, creationflags=getattr(subprocess, 'CREATE_NO_WINDOW', 0))
            process = self._process
            while process.poll() is None:
                done = len(list((folder / 'folds').glob('*/FROZEN.json'))) if (folder / 'folds').is_dir() else 0
                progress(f'TabFM ({total} held-out tests): {done}/{total} predicted '
                         f'({time.monotonic()-started:.0f} s)')
                time.sleep(1)
        self._process = None
        if process.returncode != 0 or not self._finished(folder):
            raise RuntimeError(f'TabFM run failed (exit code {process.returncode}).\nLog: {log}')
        (self.jobs / f'{name}.keys.json').write_text(json.dumps([key], indent=2), encoding='utf-8')
        self._index = None
        return folder

    def _study(self, rows, experiments, progress):
        key = self._key(rows, experiments)
        if key not in self._completed():
            self._stage(rows)
            self._run_job(key, len(rows), progress)
        return self._completed()[key]

    def _run_info(self, folder):
        if folder not in self._runs:
            shots = json.loads((folder / 'shots.json').read_text(encoding='utf-8'))
            self._runs[folder] = {shot['shot_id']: shot for shot in shots}
        return self._runs[folder]

    # GUI contract ----------------------------------------------------------
    def _fold(self, folder, shot, conditions, rows, experiments):
        row, experiment = rows[shot], experiments[shot]
        sid = experiment.shot_id
        fold = folder / 'folds' / sid
        with np.load(fold / 'prediction.npz', allow_pickle=False) as saved:
            time_s, voltage_v = saved['time_s'].copy(), saved['voltage_v'].copy()
        audit = json.loads((fold / 'audit.json').read_text(encoding='utf-8'))
        receipt = json.loads((fold / 'inference_cost.json').read_text(encoding='utf-8'))
        trigger_s = float(self._run_info(folder)[sid]['trigger_s'])
        wave = self._files.get('wave', row, lambda row: read_waveform(row))
        time_ns = wave.time_ns.to_numpy(float)
        pcd_peak = self._files.get('pcd_peak', row, read_pcd_peak)
        # TabFM's target is polarity x recorded volts; the GUI keeps the recorded sign and scale.
        curve_ns = (time_s + trigger_s - pcd_peak) * 1e9
        predicted = np.interp(time_ns, curve_ns, voltage_v * experiment.polarity / row.scope_scale_factor,
                              left=np.nan, right=np.nan)
        # The handoff leaves flops_per_sample empty when operators lack FLOP formulas; the
        # GUI counts PyTorch models that way anyway (built-in formulas only), so it uses
        # the handoff's counted total for the queried points.
        counted, per_sample = receipt.get('counted_torch_flops'), receipt.get('flops_per_sample')
        flops = (float(counted) if counted is not None else
                 float(per_sample) * len(time_s) if per_sample is not None else np.nan)
        cost = dict(inference_flops=flops,
                    prediction_samples=len(time_s), inference_seconds=receipt.get('seconds'),
                    context_fit_seconds=audit.get('fit_seconds'), scope=receipt.get('scope'))
        actual = wave.actual_v.to_numpy(float)
        train_ids = [int(str(other).removeprefix('shot')) for other in audit.get('training_shots', [])]
        return add_evaluation(dict(
            shot_id=int(row.shot_id), diode_type='SMAJ400A', conditions=conditions,
            wave=wave[['time_ns', 'actual_v']].copy(), predicted=predicted,
            score=_metrics(actual, predicted, (time_ns >= -60) & (time_ns <= 1000)),
            full=_metrics(actual, predicted), train_shot_ids=train_ids,
            model_name=self.name, model_slug=self.slug, compute_cost=cost,
            package_metrics=dict(job=str(folder), coverage_ns=(float(curve_ns[0]), float(curve_ns[-1])))))

    def model_shot(self, shot_id, *, progress=None):
        report = progress or (lambda text: None)
        conditions = self.load_smaj_conditions()
        rows, experiments = self._inputs(conditions)
        if int(shot_id) not in rows:
            raise ValueError(f'Test {shot_id} is not one of the TabFM handoff tests.')
        folder = self._study(rows, experiments, report)
        return self._fold(folder, int(shot_id), conditions, rows, experiments)

    def all_test_stats(self, *, progress=None):
        report = progress or (lambda text: None)
        conditions = self.load_smaj_conditions()
        rows, experiments = self._inputs(conditions)
        folder = self._study(rows, experiments, report)
        results = []
        for index, shot in enumerate(rows, 1):
            report(f'Tabular holdout {shot} ({index}/{len(rows)})...')
            results.append(self._fold(folder, shot, conditions, rows, experiments))
        data = pd.DataFrame([evaluation_row(result) for result in results])
        data.attrs.update(model_name=self.name, model_slug=self.slug, sensitivity_results=results,
                          coverage_note=self.coverage_note)
        return data

    def all_test_sensitivity(self, results, feature, *, progress=None):
        features = SENSITIVITY_FEATURES if feature is None else {feature: FEATURES[feature]}
        return modeled_test_sensitivity(results, features, progress=progress)
