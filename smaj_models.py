def training_mask(time_ns):
    """Time points used for training (the first 200 ns densely, the tail sparsely)."""
    time_ns = np.asarray(time_ns, dtype=float)
    keep = np.zeros(len(time_ns), bool)
    for start, end, step in TRAINING_SAMPLING:
        remainder = (time_ns - start) % step
        on_step = np.isclose(remainder, 0) | np.isclose(remainder, step)
        keep |= (time_ns >= start) & (time_ns < end) & on_step
    return keep


def _scale(values, value_range):
    high, low = value_range
    return (np.asarray(values, dtype=float) - low) / (high - low)


def read_pcd(row, time_ns=KAN_GRID_NS):
    """PCD3_B dose-rate trace aligned to its peak, as the diode loader aligns time zero."""
    path = row.waveform_csv
    header = list(pd.read_csv(path, nrows=0).columns)
    if 'PCD3_B' not in header:
        raise ValueError(f'Test {row.shot_id}: the KAN needs the PCD3_B channel from the scope export. '
                         'Uncheck this test for KAN in Choose tests…')
    index = header.index('PCD3_B')
    raw = pd.read_csv(path, usecols=[header[index-1], 'PCD3_B'])
    time_s, pcd = _scope_channel(raw, 'PCD3_B')
    relative_ns = (time_s - time_s[np.argmax(pcd)]) * 1e9
    return np.interp(time_ns, relative_ns, pcd, left=np.nan, right=np.nan)


def scenario_pcd(pcd, time_ns, baseline, condition):
    """PCD3_B trace for changed conditions: dose scales it, PCD width stretches it about the peak."""
    pcd = np.asarray(pcd, dtype=float)
    ratio = float(condition['dose_rate']) / float(baseline['dose_rate'])
    stretch = float(baseline['pcd_fwhm_ns']) / float(condition['pcd_fwhm_ns'])
    if stretch != 1:
        finite = np.isfinite(pcd)
        pcd = np.interp(time_ns * stretch, time_ns[finite], pcd[finite], left=np.nan, right=np.nan)
    return pcd * ratio


class KanPrediction(_ProfiledPrediction):
    """A trained KAN plus its input scaling; waveform() is profiled for PyTorch FLOPs."""

    def __init__(self, network, pcd_range):
        super().__init__()
        self.network = network
        self.pcd_range = pcd_range
        self.regression_coefficients = sum(parameter.numel() for parameter in network.parameters()
                                           if parameter.requires_grad)

    @staticmethod
    def features(time_ns, pcd, bias_v, load_ohm, pcd_range):
        time_us = (np.asarray(time_ns, dtype=float) - KAN_GRID_NS[0]) / 1000
        columns = [_scale(time_us, TIME_RANGE_US), _scale(pcd, pcd_range),
                   np.full(len(time_us), _scale(bias_v, BIAS_RANGE)),
                   np.full(len(time_us), _scale(np.log10(load_ohm), LOG_LOAD_RANGE))]
        return np.column_stack(columns).astype(np.float32)

    def waveform(self, time_ns, pcd, condition):
        """Predicted volts at each time; NaN where the PCD3_B trace has no sample."""
        x = self.features(time_ns, pcd, float(condition['bias_v']), float(condition['load_ohm']),
                          self.pcd_range)
        valid = np.isfinite(x).all(axis=1)
        output = np.full(len(x), np.nan)
        if valid.any():
            inputs = torch.from_numpy(x[valid]).to(self.network.device)
            scaled = self._profile('waveform', self.network.forward, inputs)
            output[valid] = scaled.detach().cpu().numpy()[:, 0] * (VOLT_RANGE[0]-VOLT_RANGE[1]) + VOLT_RANGE[1]
        self.prediction_samples = len(time_ns)
        return output


def new_network(device='cpu'):
    """The team's KAN architecture; symbolic branch off (unused, and costly)."""
    # pykan rewrites the width list in place ([4, ...] -> [[4, 0], ...]); pass a copy.
    return kan.KAN(width=list(WIDTH), grid=SPLINE_GRID, k=SPLINE_ORDER, seed=SEED, grid_range=[0, 1],
                   device=str(device), auto_save=False, symbolic_enabled=False)


def training_arrays(training):
    """Scaled inputs, targets and PCD range from the sampled points of the training tests.

    training: list of (wave, pcd, condition) for the training tests only.
    """
    stacked = []
    for wave, pcd, condition in training:
        time = wave.time_ns.to_numpy(float)
        volt = wave.actual_v.to_numpy(float)
        keep = training_mask(time) & np.isfinite(volt) & np.isfinite(pcd)
        stacked.append((time[keep], pcd[keep], volt[keep], condition))
    all_pcd = np.concatenate([pcd for _, pcd, _, _ in stacked])
    pcd_range = (float(all_pcd.max()), float(all_pcd.min()))
    x = np.vstack([KanPrediction.features(time, pcd, float(condition['bias_v']),
                                          float(condition['load_ohm']), pcd_range)
                   for time, pcd, _, condition in stacked])
    y = _scale(np.concatenate([volt for _, _, volt, _ in stacked]), VOLT_RANGE).astype(np.float32)
    return x, y, pcd_range


def network_path(x, y, cache_dir=CACHE_DIR):
    """Saved-network file; the training inputs and settings fully determine the network."""
    key = sha256(x.tobytes() + y.tobytes() + repr((CACHE_VERSION, PYKAN_VERSION, WIDTH, SPLINE_GRID,
                 SPLINE_ORDER, SEED, sorted(FIT_SETTINGS.items()))).encode()).hexdigest()[:32]
    return Path(cache_dir) / f'{key}.pt'


def train_kan(training, progress=None, cache_dir=CACHE_DIR):
    """Fit the team's KAN on the training tests, or load the saved identical fit.

    training: list of (wave, pcd, condition) for the training tests only.
    """
    report = progress or (lambda text: None)
    x, y, pcd_range = training_arrays(training)
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    cached = network_path(x, y, cache_dir)
    if cached.is_file():
        try:
            saved = torch.load(cached, map_location=device, weights_only=True)
            network = new_network(device)
            network.load_state_dict(saved['state'])
            network.save_act = False
            network.eval()
            report(f'Reusing the saved KAN for these {len(training)} training tests.')
            return KanPrediction(network, tuple(float(value) for value in saved['pcd_range']))
        except (OSError, RuntimeError, KeyError):
            pass  # Retrain if the saved network cannot be read.
    monitor = np.random.default_rng(SEED).choice(len(x), min(MONITOR_POINTS, len(x)), replace=False)
    dataset = {
        'train_input': torch.from_numpy(x).to(device),
        'train_label': torch.from_numpy(y).reshape(-1, 1).to(device),
        'test_input': torch.from_numpy(x[monitor]).to(device),
        'test_label': torch.from_numpy(y[monitor]).reshape(-1, 1).to(device),
    }
    report(f'Training KAN on {len(x):,} samples from {len(training)} tests '
           f'({FIT_SETTINGS["steps"]} Adam steps; a few minutes)...')
    torch.set_num_threads(max(1, os.cpu_count() or 1))
    with redirect_stdout(io.StringIO()), redirect_stderr(io.StringIO()):
        network = new_network(device)
        network.save_act = False  # No activation caching: lamb is 0 and nothing reads it.
        network.fit(dataset, **FIT_SETTINGS)
    network.save_act = False
    network.eval()
    try:
        cached.parent.mkdir(parents=True, exist_ok=True)
        partial = cached.with_suffix('.tmp')
        torch.save(dict(state=network.state_dict(), pcd_range=list(pcd_range)), partial)
        partial.replace(cached)
    except OSError:
        pass  # Caching is only a speed-up.
    return KanPrediction(network, pcd_range)


class KanBackend:
    supports_input_sensitivity = True
    name = NAME
    slug = SLUG
    description = ('A Kolmogorov-Arnold network predicts the voltage at each time from the PCD3_B '
                   'dose-rate trace, bias and load. The selected waveform is excluded from training.')

    def __init__(self, metadata=METADATA, cache_dir=CACHE_DIR):
        self.metadata = Path(metadata)
        self.cache_dir = Path(cache_dir)
        self._files = ScopeFileCache()
        self._networks = {}

    def load_smaj_conditions(self):
        return load_smaj_conditions(self.metadata)

    def clear_cache(self):
        self._files.clear()
        self._networks.clear()

    def _wave(self, row):
        return self._files.get('wave', row, lambda row: read_waveform(row))

    def _pcd(self, row):
        return self._files.get('pcd', row, read_pcd)

    def _training_inputs(self, row):
        """Training test's aligned voltage and PCD3_B trace on the standard grid."""
        wave = self._wave(row)
        if not np.array_equal(wave.time_ns.to_numpy(float), KAN_GRID_NS):
            raise ValueError(f'Test {row.shot_id}: the KAN needs a scope export on the standard time grid.')
        return wave, self._pcd(row)

    def _training_set(self, shot_id, conditions, progress=None):
        """The other tests' inputs for one holdout: (train conditions, [(wave, pcd, condition)])."""
        train = conditions.loc[conditions.shot_id.ne(shot_id)].reset_index(drop=True)
        if len(train) < 3:
            raise ValueError(f'Test {shot_id} needs at least three other SMAJ400A tests.')
        report = progress or (lambda text: None)
        training = []
        for index, row in enumerate(train.itertuples(), 1):
            report(f'Loading KAN training test {row.shot_id} ({index}/{len(train)})...')
            wave, pcd = self._training_inputs(row)
            training.append((wave, pcd, row._asdict()))
        return train, training

    def _network(self, shot_id, conditions, progress=None):
        """Train (or reuse) the KAN for one holdout from the other tests only."""
        train_ids = tuple(int(shot) for shot in conditions.shot_id if shot != shot_id)
        key = (int(shot_id), train_ids)
        if key not in self._networks:
            _, training = self._training_set(shot_id, conditions, progress)
            self._networks[key] = train_kan(training, progress, self.cache_dir)
        return self._networks[key], list(train_ids)

    work_label = 'held-out tests need a trained network'
    minutes_per_item = 3.

    def missing_work(self, progress=None):
        """(missing, total) for the comparison's prompt; see missing_networks."""
        return self.missing_networks(progress)

    def missing_networks(self, progress=None):
        """(holdouts with no saved network, all holdouts) for the current test selection."""
        report = progress or (lambda text: None)
        conditions = self.load_smaj_conditions()
        missing = 0
        for index, shot_id in enumerate(conditions.shot_id, 1):
            report(f'Checking saved KAN networks ({index}/{len(conditions)})...')
            if (int(shot_id), tuple(int(shot) for shot in conditions.shot_id if shot != shot_id)) in self._networks:
                continue
            _, training = self._training_set(int(shot_id), conditions)
            x, y, _ = training_arrays(training)
            missing += not network_path(x, y, self.cache_dir).is_file()
        return missing, len(conditions)

    def _result(self, shot_id, conditions, network, train_ids):
        row = next(conditions.loc[conditions.shot_id.eq(shot_id)].itertuples())
        condition = row._asdict()
        pcd = self._pcd(row)
        prediction = KanPrediction(network.network, network.pcd_range)
        predicted = prediction.waveform(KAN_GRID_NS, pcd, condition)
        # Held-out voltage is first read here, after the prediction is fixed.
        wave = self._wave(row)
        time = wave.time_ns.to_numpy(float)
        if not np.array_equal(time, KAN_GRID_NS):
            raise ValueError(f'Test {shot_id}: the KAN needs a scope export on the standard time grid.')
        actual = wave.actual_v.to_numpy(float)
        return add_evaluation(dict(
            shot_id=int(shot_id), diode_type='SMAJ400A', conditions=conditions,
            wave=wave[['time_ns', 'actual_v']].copy(), predicted=predicted,
            score=_metrics(actual, predicted, (time >= -60) & (time <= 1000)),
            full=_metrics(actual, predicted), train_shot_ids=train_ids,
            model_name=self.name, model_slug=self.slug, compute_cost=prediction.compute_cost,
            _sensitivity_context=dict(kind='kan', network=network, pcd=pcd, condition=condition)))

    def model_shot(self, shot_id, *, progress=None):
        conditions = self.load_smaj_conditions()
        if shot_id not in set(conditions.shot_id):
            raise ValueError(f'Test {shot_id} is not an available SMAJ400A test.')
        network, train_ids = self._network(shot_id, conditions, progress)
        return self._result(shot_id, conditions, network, train_ids)

    def all_test_stats(self, *, progress=None):
        report = progress or (lambda text: None)
        conditions = self.load_smaj_conditions()
        rows, results = [], []
        for index, shot_id in enumerate(conditions.shot_id, 1):
            prefix = f'KAN holdout {shot_id} ({index}/{len(conditions)})'
            report(f'{prefix}...')
            network, train_ids = self._network(
                int(shot_id), conditions, lambda text, prefix=prefix: report(f'{prefix}: {text}'))
            result = self._result(int(shot_id), conditions, network, train_ids)
            results.append(result)
            rows.append(evaluation_row(result))
        data = pd.DataFrame(rows)
        data.attrs.update(model_name=self.name, model_slug=self.slug, sensitivity_results=results)
        return data

    def input_sensitivity(self, result, feature, *, progress=None, values=None):
        context = result.get('_sensitivity_context')
        if not context or context.get('kind') != 'kan':
            raise ValueError('Run the KAN prediction before measuring input sensitivity.')
        time = result['wave'].time_ns.to_numpy(float)
        network, pcd, baseline = context['network'], context['pcd'], context['condition']

        def predict(condition):
            condition = condition.iloc[0]
            trace = scenario_pcd(pcd, time, baseline, condition)
            return KanPrediction(network.network, network.pcd_range).waveform(time, trace, condition)

        sensitivity = profile_sweep(
            result=result, conditions=result['conditions'], shot_id=result['shot_id'], feature=feature,
            time_ns=time, baseline_prediction=result['predicted'], predict=predict,
            progress=progress, values=values)
        sensitivity.update(shot_id=result['shot_id'], model_name=result['model_name'])
        return sensitivity

    def all_test_sensitivity(self, results, feature, *, progress=None):
        features = SENSITIVITY_FEATURES if feature is None else {feature: FEATURES[feature]}
        return modeled_test_sensitivity(results, features, progress=progress)


