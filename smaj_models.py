# In-memory cache of parsed scope exports, shared by the GUI's model backends.
#
# Parsing a ~10 MB scope CSV dominated repeated holdouts: each holdout re-read
# every training file. Entries are keyed by file path, size and modification
# time plus the metadata scale factors, so edited files or calibrations are
# re-read while unchanged ones are parsed once per session.

from pathlib import Path


class ScopeFileCache:
    def __init__(self):
        self._entries = {}

    def clear(self):
        self._entries.clear()

    def get(self, kind, row, read):
        """Return read(row), parsing the file again only if it or its scaling changed."""
        path = Path(row.waveform_csv)
        stat = path.stat()
        key = (str(path), stat.st_size, stat.st_mtime_ns,
               float(row.scope_scale_factor), float(row.cached_scope_scale_factor))
        cached = self._entries.get((kind, int(row.shot_id)))
        if cached is None or cached[0] != key:
            cached = (key, read(row))
            self._entries[(kind, int(row.shot_id))] = cached
        return cached[1]


