def window_mask(time, view):
    if view not in VIEWS:
        raise ValueError(f'Unknown waveform window: {view}')
    valid = np.isfinite(time)
    if view in WINDOWS:
        start, end = WINDOWS[view]
        return valid & (time >= start) & (time <= end)
    return valid


def window_score(time, measured, predicted, view):
    """Waveform RMSE and R² on the window's observed samples, as the backends score them."""
    valid = window_mask(time, view) & np.isfinite(measured) & np.isfinite(predicted)
    if valid.sum() < 5:
        return dict(rmse_v=float('nan'), mae_v=float('nan'), r2=float('nan'), n_samples=int(valid.sum()))
    residual = measured[valid]-predicted[valid]
    sst = float(np.sum((measured[valid]-measured[valid].mean())**2))
    return dict(rmse_v=float(np.sqrt(np.mean(residual**2))), mae_v=float(np.mean(np.abs(residual))),
                r2=1-float(np.sum(residual**2))/sst if sst > 1e-15 else np.nan, n_samples=int(valid.sum()))


def normalized_percent(error, reference):
    if not np.isfinite(reference) or reference <= 1e-12:
        return float('nan')
    return float(100 * error / reference)


def peak_magnitude(time, voltage, view='prompt', common=None):
    """Largest baseline-relative magnitude on observed samples in this window."""
    valid = np.isfinite(time) & np.isfinite(voltage)
    pre = valid & (time >= -150) & (time < -60)
    selected = valid & window_mask(time, view)
    if common is not None:
        selected &= common
    if pre.sum() < 3 or selected.sum() < 5:
        return float('nan')
    return float(np.max(np.abs(voltage[selected] - np.median(voltage[pre]))))


def phase_alignment(time, measured, predicted, view='prompt'):
    """Masked, overlap-normalized correlation; positive lag means prediction late.

    Retain bounded/weak estimates instead of discarding them. For tied maxima,
    select the smallest absolute lag deterministically and flag the ambiguity.
    Truly flat signals or inadequate data have no measurable alignment.
    """
    answer = dict(phase_error_ns=np.nan, phase_correlation=np.nan,
                  phase_status='Insufficient coverage', phase_search_limit_ns=np.nan)
    mask = window_mask(time, view)
    t, actual, pred = time[mask], measured[mask], predicted[mask]
    common = np.flatnonzero(np.isfinite(actual) & np.isfinite(pred))
    if len(common) < 8:
        return answer
    selection = slice(common[0], common[-1]+1)
    t, actual, pred = t[selection], actual[selection], pred[selection]
    dt = float(np.median(np.diff(t)))
    if dt <= 0 or not np.allclose(np.diff(t), dt, rtol=1e-6, atol=1e-8):
        answer['phase_status'] = 'Nonuniform time grid'
        return answer
    ma, mp = np.isfinite(actual).astype(float), np.isfinite(pred).astype(float)
    # Zeros are placeholders only: masks exclude them from every overlap sum.
    a = np.where(ma, actual-np.mean(actual[ma.astype(bool)]), 0.)
    p = np.where(mp, pred-np.mean(pred[mp.astype(bool)]), 0.)
    count = correlate(mp, ma, method='direct')
    count_safe = np.maximum(count, 1.)
    sum_a = correlate(mp, a, method='direct')
    sum_p = correlate(p, ma, method='direct')
    var_a = np.maximum(correlate(mp, a*a, method='direct') - sum_a**2/count_safe, 0.)
    var_p = np.maximum(correlate(p*p, ma, method='direct') - sum_p**2/count_safe, 0.)
    covariance = correlate(p, a, method='direct') - sum_a*sum_p/count_safe
    lags = correlation_lags(len(p), len(a))
    limit = int(np.floor((len(t)-1)*.25))
    answer['phase_search_limit_ns'] = limit*dt
    enough = count >= max(8, .75*min(ma.sum(), mp.sum()))
    varying = ((var_a > 1e-12*max(float(np.dot(a, a)), 1e-12)) &
               (var_p > 1e-12*max(float(np.dot(p, p)), 1e-12)))
    eligible = (np.abs(lags) <= limit) & enough & varying
    if not eligible.any():
        answer['phase_status'] = 'Flat signal or insufficient overlap'
        return answer
    correlation = np.full(len(lags), -np.inf)
    correlation[eligible] = np.clip(covariance[eligible]/np.sqrt(var_a[eligible]*var_p[eligible]), -1, 1)
    best = int(np.argmax(correlation))
    ties = np.flatnonzero(eligible & np.isclose(correlation, correlation[best], rtol=0, atol=1e-10))
    ambiguous = len(ties) > 1 and np.ptp(lags[ties]) > 1
    if ambiguous:
        best = int(ties[np.argmin(np.abs(lags[ties]))])
    cautions = []
    if abs(lags[best]) == limit:
        cautions.append(f'Search-limit estimate (±{limit*dt:g} ns)')
    if ambiguous:
        cautions.append('Ambiguous alignment; closest-to-zero best lag')
    if correlation[best] <= 0:
        cautions.append('Weak alignment; no positive correlation')
    offset = 0.
    left, center, right = correlation[best-1:best+2]
    curvature = left-2*center+right
    if not cautions and center < 1-1e-12 and np.isfinite([left, center, right]).all() and curvature < -1e-15:
        offset = float(np.clip(.5*(left-right)/curvature, -.5, .5))
    answer.update(phase_error_ns=float((lags[best]+offset)*dt),
                  phase_correlation=float(correlation[best]), phase_status='; '.join(cautions) or 'OK')
    return answer


def rms_magnitudes(time, measured, predicted, view='full'):
    """Baseline-relative RMS values on identical observed samples in the window."""
    common = window_mask(time, view) & np.isfinite(measured) & np.isfinite(predicted)
    count = int(common.sum())
    values = []
    for voltage in (measured, predicted):
        pre = np.isfinite(time) & np.isfinite(voltage) & (time >= -150) & (time < -60)
        if pre.sum() < 3 or count < 5:
            values.append(float('nan'))
        else:
            relative = voltage[common] - np.median(voltage[pre])
            values.append(float(np.sqrt(np.mean(relative**2))))
    return *values, count


def add_evaluation(result):
    """Evaluate both windows without changing predictions or raw score fields."""
    wave = result['wave']
    time = wave.time_ns.to_numpy(float)
    measured = wave.actual_v.to_numpy(float)
    predicted = np.asarray(result['predicted'], dtype=float)
    if predicted.shape != measured.shape:
        raise ValueError('Predicted and measured waveforms must have matching shapes.')
    common = np.isfinite(time) & np.isfinite(measured) & np.isfinite(predicted)
    condition = result['conditions'].loc[result['conditions'].shot_id.eq(result['shot_id'])].iloc[0]
    width = float(condition.pcd_fwhm_ns)
    result['evaluations'] = {}
    for view in VIEWS:
        actual_peak = peak_magnitude(time, measured, view, common)
        predicted_peak = peak_magnitude(time, predicted, view, common)
        actual_rms, predicted_rms, count = rms_magnitudes(time, measured, predicted, view)
        phase = phase_alignment(time, measured, predicted, view)
        if SCORE_KEYS[view] not in result:
            result[SCORE_KEYS[view]] = window_score(time, measured, predicted, view)
        score = result[SCORE_KEYS[view]]
        score['nrmse_pct'] = normalized_percent(score['rmse_v'], actual_peak)
        result['evaluations'][view] = dict(
            nrmse_pct=score['nrmse_pct'], r2=score['r2'],
            measured_peak_v=actual_peak, predicted_peak_v=predicted_peak,
            peak_nrmse_pct=normalized_percent(abs(predicted_peak-actual_peak), actual_peak),
            measured_rms_v=actual_rms, predicted_rms_v=predicted_rms,
            magnitude_nrmse_pct=normalized_percent(abs(predicted_rms-actual_rms), actual_peak),
            magnitude_samples=count, **phase, pcd_width_ns=width,
            phase_nrmse_pct=normalized_percent(abs(phase['phase_error_ns']), width))
    result['evaluation'] = result['evaluations']['prompt']
    return result


def evaluation_row(result):
    if 'evaluations' not in result:
        add_evaluation(result)
    cost = result.get('compute_cost', {})
    row = dict(shot_id=result['shot_id'], training_tests=len(result['train_shot_ids']))
    for view in VIEWS:
        row.update({f'{view}_{key}': result['evaluations'][view][key] for key in WINDOW_HEADINGS})
    if 'inference_flops' in cost:
        row['pytorch_flops_per_prediction'] = cost['inference_flops']
    else:
        row['operations_per_prediction'] = cost.get('inference_flops_est', np.nan)
    row.update({key: cost.get(key, np.nan) for key in (
        'inference_special_evals', 'regression_coefficients', 'prediction_samples')})
    return row


def stats_with_totals(data):
    """Equal-test RMS of normalized errors; means for other numeric columns."""
    values = data.drop(columns='shot_id').select_dtypes(include='number').replace([np.inf, -np.inf], np.nan)
    totals = values.mean().to_dict()
    for column in values:
        if column.endswith('_nrmse_pct'):
            totals[column] = float(np.sqrt((values[column]**2).mean()))
    totals['shot_id'] = 'Total averages'
    for view in VIEWS:
        key = f'{view}_phase_error_ns'
        if key in data:
            totals[f'{view}_phase_status'] = f'{int(np.isfinite(data[key]).sum())}/{len(data)} available'
    result = pd.concat([data, pd.DataFrame([totals], columns=data.columns)], ignore_index=True)
    result.attrs.update(data.attrs)
    return result


def batch_columns(view='prompt', *, pytorch=False):
    if view not in VIEWS:
        raise ValueError(f'Unknown waveform window: {view}')
    columns = ['shot_id', *(f'{view}_{key}' for key in REPORTED_STATS)]
    if view == 'full':
        columns.append('pytorch_flops_per_prediction' if pytorch else 'operations_per_prediction')
    return columns


def batch_report(data, view='prompt'):
    """The same window-specific performance columns and totals for table/CSV."""
    return stats_with_totals(data).loc[:, batch_columns(view, pytorch='pytorch_flops_per_prediction' in data)]


def detail_rows(result, view='prompt'):
    """Normalized stats only; measured/predicted voltages stay internal references."""
    if 'evaluations' not in result:
        add_evaluation(result)
    values = result['evaluations'][view]
    for key in REPORTED_STATS:
        heading = WINDOW_HEADINGS[key]
        unit = heading[heading.rfind('(')+1:-1] if heading.endswith(')') else ''
        yield heading.replace(f' ({unit})', ''), values[key], unit
    if view == 'full':
        cost = result.get('compute_cost', {})
        if 'inference_flops' in cost:
            yield HEADINGS['pytorch_flops_per_prediction'], cost['inference_flops'], 'FLOPs'
        else:
            yield HEADINGS['operations_per_prediction'], cost.get('inference_flops_est', np.nan), 'operations'


